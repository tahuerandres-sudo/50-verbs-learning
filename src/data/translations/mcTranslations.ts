/**
 * Gets a clean, natural, complete Spanish translation for any multiple-choice question.
 */
export function getQuestionSpanishTranslation(
  questionId: string,
  englishText: string,
  verbName?: string,
  verbEs?: string
): string {
  // 1. Direct dictionary match with complete sentence translation
  if (MC_QUESTION_TRANSLATIONS[questionId]) {
    return MC_QUESTION_TRANSLATIONS[questionId];
  }

  const text = englishText.trim();

  // 2. High-frequency common patterns
  if (text === 'Choose the correct sentence:' || text === 'Choose the correct sentence.') {
    return 'Elige la oración correcta:';
  }
  if (text === 'Which sentence is grammatically correct?' || text === 'Which sentence is grammatically correct:') {
    return '¿Cuál oración es gramaticalmente correcta?';
  }
  if (text === 'Choose the correct question format:' || text === 'Choose the correct question format.') {
    return 'Elige el formato de pregunta correcto:';
  }

  // 3. Past simple patterns
  if (text.toLowerCase().includes('past simple') || text.toLowerCase().includes('past tense')) {
    const vMatch = text.match(/\"([^\"]+)\"/) || text.match(/'([^']+)'/);
    const verb = vMatch ? vMatch[1] : (verbName || '');
    return `¿Cuál es la forma en Pasado Simple del verbo "${verb}"${verbEs ? ` (${verbEs})` : ''}?`;
  }

  // 4. Past participle patterns
  if (text.toLowerCase().includes('past participle')) {
    const vMatch = text.match(/\"([^\"]+)\"/) || text.match(/'([^']+)'/);
    const verb = vMatch ? vMatch[1] : (verbName || '');
    return `¿Cuál es el Participio Pasado del verbo "${verb}"${verbEs ? ` (${verbEs})` : ''}?`;
  }

  // 5. Spanish translation of verb question
  if (text.toLowerCase().includes('spanish translation')) {
    const vMatch = text.match(/\"([^\"]+)\"/) || text.match(/'([^']+)'/);
    const verb = vMatch ? vMatch[1] : (verbName || '');
    return `¿Cuál es la traducción al español del verbo "${verb}"?`;
  }

  // 6. Phrasal verb meanings
  if (text.toLowerCase().includes('phrasal verb')) {
    const vMatch = text.match(/\"([^\"]+)\"/) || text.match(/'([^']+)'/);
    return vMatch ? `¿Qué significa la frase verbal "${vMatch[1]}"?` : '¿Qué significa este verbo frasal?';
  }

  // 7. General fallback
  return englishText;
}
